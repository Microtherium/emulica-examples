void ADC_Demo(void) {
  uint16_t adc_value;
  uint8_t adc_bytes[2];

  if (HAL_ADC_Start(&hadc1) != HAL_OK) {
    Error_Handler();
  }

  if (HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY) != HAL_OK) {
    Error_Handler();
  }

  adc_value = HAL_ADC_GetValue(&hadc1) & 0x0FFF;
  adc_bytes[0] = (uint8_t)(adc_value >> 8);
  adc_bytes[1] = (uint8_t)(adc_value & 0xFF);

  HAL_I2C_Master_Transmit(&hi2c1, TMP117_ADDR << 1, adc_bytes, 2, HAL_MAX_DELAY);

  if (HAL_ADC_Stop(&hadc1) != HAL_OK) {
    Error_Handler();
  }
}

void SPI_Demo(void) {
  // SPI Flash write example: Send 0x000523 to address 0x0000CA
  memset(spi_tx_buffer, 0, sizeof(spi_tx_buffer));

  // Write Enable command: 0x06 (Needed before Page Program)
  spi_tx_buffer[0] = 0x06;
  if (EMULICA_IS_TESTING) {
    spi_tx_buffer[0] = SPI_VAL_TEST;
  }
  HAL_GPIO_WritePin(CS_I2C_SPI_GPIO_Port, CS_I2C_SPI_Pin, GPIO_PIN_RESET);
  HAL_SPI_Transmit(&hspi1, spi_tx_buffer, 1, HAL_MAX_DELAY);
  HAL_GPIO_WritePin(CS_I2C_SPI_GPIO_Port, CS_I2C_SPI_Pin, GPIO_PIN_SET);

  HAL_Delay(1); // Small delay to latch the write enable

  // Page Program command: 0x02 + 24-bit address + data payload
  spi_tx_buffer[0] = 0x02; // Page Program command
  spi_tx_buffer[1] = 0x00; // Address byte 1 (MSB)
  spi_tx_buffer[2] = 0x00; // Address byte 2
  spi_tx_buffer[3] = 0xCA; // Address byte 3 (LSB)
  spi_tx_buffer[4] = 0x00; // Data byte 1
  spi_tx_buffer[5] = 0x15; // Data byte 2
  spi_tx_buffer[6] = 0x21; // Data byte 3

  // CS low
  HAL_GPIO_WritePin(CS_I2C_SPI_GPIO_Port, CS_I2C_SPI_Pin, GPIO_PIN_RESET);

  // Send write command and data
  HAL_SPI_Transmit(&hspi1, spi_tx_buffer, 7, HAL_MAX_DELAY);

  // CS high
  HAL_GPIO_WritePin(CS_I2C_SPI_GPIO_Port, CS_I2C_SPI_Pin, GPIO_PIN_SET);

  // Toggle orange LED on successful SPI communication
  HAL_GPIO_TogglePin(LD5_GPIO_Port, LD5_Pin);
}
